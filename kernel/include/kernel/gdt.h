#define ACCESS_BIT6_DATA_DIRECTION_TOP 0
#define ACCESS_BIT6_CODE_EXEC_SAME_DPL 0
#define ACCESS_BIT6_CODE_EXEC_EQUAL_OR_LOWER_DPL 0b00000100

#define ACCESS_BIT7_DATA_ALLOW_WRITING 0b00000010
#define ACCESS_BIT7_DATA_NO_WRITING 0
#define ACCESS_BIT7_CODE_ALLOW_READING 0b00000010
#define ACCESS_BIT7_CODE_NO_READING 0

#define ACCESS_BIT8_NOT_CPU_ACCESSED 0

